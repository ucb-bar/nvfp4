// FP32 arithmetic, RNE, with signed flush-to-zero (FTZ) inputs and outputs. The functions are the
// combinational reference of fp32_alu. exp2 and reciprocal approximate the PTX SFU operations
// (see docs/compute.md).
package fp32_pkg;
  localparam logic [31:0] QNAN = 32'h7fff_ffff;
  localparam logic [31:0] ONE = 32'h3f80_0000;
  localparam logic [31:0] NEG_INF = 32'hff80_0000;

  function automatic logic [31:0] ftz(input logic [31:0] x);
    return x[30:23] == 0 ? {x[31], 31'd0} : x;
  endfunction

  function automatic logic is_nan(input logic [31:0] x);
    return x[30:23] == 255 && x[22:0] != 0;
  endfunction

  function automatic logic [63:0] shift_jam(input logic [63:0] x, input int shift);
    if (shift <= 0) return x;
    if (shift >= 64) return {63'd0, |x};
    return (x >> shift) | 64'((x << (64 - shift)) != 0);
  endfunction

  // Pack mag * 2^exponent, retaining all discarded bits for RNE.
  function automatic logic [31:0] pack_rne(input logic sign_bit, input logic [63:0] mag,
                                         input int exponent);
    int leading, unbiased, shift;
    logic [63:0] rounded, remainder, halfway;
    leading = 0;
    for (int b = 0; b < 64; b++) if (mag[b]) leading = b;
    if (mag == 0) return {sign_bit, 31'd0};
    unbiased = exponent + leading;
    shift = leading - 23;
    // Allow rounding a value just below the smallest normal into that normal.
    if (unbiased < -126) shift = -149 - exponent;
    rounded = mag;
    if (shift > 0 && shift < 64) begin
      rounded = mag >> shift;
      remainder = mag & ((64'd1 << shift) - 1);
      halfway = 64'd1 << (shift - 1);
      rounded = rounded + 64'(remainder > halfway || (remainder == halfway && rounded[0]));
    end else if (shift >= 64) rounded = 0;
    else if (shift < 0) rounded = mag << (-shift);
    if (unbiased < -126) begin
      if (rounded < 64'h800000) return {sign_bit, 31'd0};
      unbiased = -126;
    end
    if (rounded[24]) begin
      rounded = rounded >> 1;
      unbiased++;
    end
    if (unbiased > 127) return {sign_bit, 8'hff, 23'd0};
    return {sign_bit, 8'(unbiased + 127), rounded[22:0]};
  endfunction

  function automatic logic [31:0] fp_add(input logic [31:0] a_in, b_in);
    logic [31:0] a, b, swap;
    logic [63:0] large_sig, small_sig, magnitude;
    int exponent_a, exponent_b;
    a = ftz(a_in); b = ftz(b_in);
    if (is_nan(a) || is_nan(b)) return QNAN;
    if (a[30:23] == 255 || b[30:23] == 255) begin
      if (a[30:23] == 255 && b[30:23] == 255 && a[31] != b[31]) return QNAN;
      return a[30:23] == 255 ? a : b;
    end
    if (a[30:0] == 0 && b[30:0] == 0) return {a[31] & b[31], 31'd0};
    if (a[30:0] == 0) return b;
    if (b[30:0] == 0) return a;
    if (a[30:0] < b[30:0]) begin swap = a; a = b; b = swap; end
    exponent_a = int'(a[30:23]) - 127;
    exponent_b = int'(b[30:23]) - 127;
    large_sig = {37'd0, 1'b1, a[22:0], 3'd0};
    small_sig = shift_jam({37'd0, 1'b1, b[22:0], 3'd0}, exponent_a - exponent_b);
    magnitude = a[31] == b[31] ? large_sig + small_sig : large_sig - small_sig;
    return magnitude == 0 ? 32'd0 : pack_rne(a[31], magnitude, exponent_a - 26);
  endfunction

  function automatic logic [31:0] fp_mul(input logic [31:0] a_in, b_in);
    logic [31:0] a, b;
    logic sign_bit;
    logic [47:0] product;
    a = ftz(a_in); b = ftz(b_in); sign_bit = a[31] ^ b[31];
    if (is_nan(a) || is_nan(b)) return QNAN;
    if (a[30:23] == 255 || b[30:23] == 255) begin
      if (a[30:0] == 0 || b[30:0] == 0) return QNAN;
      return {sign_bit, 8'hff, 23'd0};
    end
    if (a[30:0] == 0 || b[30:0] == 0) return {sign_bit, 31'd0};
    product = {1'b1, a[22:0]} * {1'b1, b[22:0]};
    return pack_rne(sign_bit, {16'd0, product}, int'(a[30:23]) + int'(b[30:23]) - 300);
  endfunction

  function automatic logic [31:0] fp_max(input logic [31:0] a_in, b_in);
    logic [31:0] a, b;
    a = ftz(a_in); b = ftz(b_in);
    if (is_nan(a)) return is_nan(b) ? QNAN : b;
    if (is_nan(b)) return a;
    if (a[30:0] == 0 && b[30:0] == 0) return {a[31] & b[31], 31'd0};
    if (a[31] != b[31]) return a[31] ? b : a;
    return (a[30:0] > b[30:0]) ^ a[31] ? a : b;
  endfunction

  // ROMs generated by scripts/gen_sfu_tables.py, integer constants in Q1.31 / Q2.30.
  `include "sfu_tables.svh"

  function automatic logic [31:0] fp_exp2(input logic [31:0] x_in);
    logic [31:0] x;
    logic signed [63:0] fixed_x;
    logic [23:0] fraction;
    logic [31:0] residual, polynomial, base;
    logic [63:0] product;
    int exponent, integer_part;
    x = ftz(x_in);
    if (is_nan(x)) return QNAN;
    if (x[30:0] == 0) return ONE;
    if (x[30:0] >= 31'h43000000) return x[31] ? 32'd0 : 32'h7f800000; // |x| >= 128
    exponent = int'(x[30:23]) - 127;
    fixed_x = $signed({40'd0, 1'b1, x[22:0]});
    if (exponent >= -1) fixed_x = fixed_x <<< (exponent + 1);
    else fixed_x = fixed_x >>> (-exponent - 1);
    if (x[31]) fixed_x = -fixed_x;
    integer_part = int'(fixed_x >>> 24);
    fraction = fixed_x[23:0];
    residual = {7'd0, fraction[17:0], 7'd0};
    // Cubic exp2 of residual in [0,1/64); Q1.31 Horner evaluation.
    product = 64'd119194166 * residual;
    polynomial = 32'((product + 64'h40000000) >> 31) + 32'd515882496;
    product = 64'(polynomial) * residual;
    polynomial = 32'((product + 64'h40000000) >> 31) + 32'd1488522236;
    product = 64'(polynomial) * residual;
    polynomial = 32'((product + 64'h40000000) >> 31) + 32'h80000000;
    base = exp2_base(int'(fraction[23:18]));
    product = 64'(base) * polynomial;
    return pack_rne(1'b0, (product + 64'h40000000) >> 31, integer_part - 31);
  endfunction

  function automatic logic [31:0] fp_recip(input logic [31:0] x_in);
    logic [31:0] x, mantissa, estimate, correction;
    logic [63:0] product;
    x = ftz(x_in);
    if (is_nan(x)) return QNAN;
    if (x[30:0] == 0) return {x[31], 8'hff, 23'd0};
    if (x[30:23] == 255) return {x[31], 31'd0};
    mantissa = {1'b0, 1'b1, x[22:0], 7'd0}; // Q2.30, [1,2)
    estimate = recip_seed(int'(x[22:16]));
    for (int iteration = 0; iteration < 2; iteration++) begin
      product = 64'(mantissa) * estimate;
      correction = 32'h80000000 - 32'((product + 64'h20000000) >> 30);
      product = 64'(estimate) * correction;
      estimate = 32'((product + 64'h20000000) >> 30);
    end
    return pack_rne(x[31], {32'd0, estimate}, 127 - int'(x[30:23]) - 30);
  endfunction
endpackage
