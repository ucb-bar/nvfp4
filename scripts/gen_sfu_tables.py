"""Write the exp2 and reciprocal ROMs of fp32_pkg to fpga/compute/sfu_tables.svh."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
lines = ['// Generated by scripts/gen_sfu_tables.py; do not edit by hand.']
for name, size, value in [('exp2_base', 64, lambda i: 2 ** (i / 64) * 2 ** 31),
                          ('recip_seed', 128, lambda i: 2 ** 30 / (1 + (i + 0.5) / 128))]:
    lines += [f'  function automatic logic [31:0] {name}(input int index);', '    case (index)']
    lines += [f"      {i}: return 32'h{round(value(i)):08x};" for i in range(size)]
    lines += ["      default: return 32'd0;", '    endcase', '  endfunction', '']
(root / 'fpga/compute/sfu_tables.svh').write_text('\n'.join(lines))
